// Builds public/favicon.svg: the home screen's Earth, drawn from the same
// world-atlas land data and the same three colours Globe.jsx paints its
// texture with, plus the design system's hard 3px offset shadow.
//
// A favicon is mostly seen at 16px, so detail that reads at 64px turns into
// noise: there are no graticule lines, the coastline stroke is thin enough to
// vanish below 32px (it only shows on large renders, where it matches the
// globe), and landmasses too small to survive at tab size are dropped (which also keeps
// the file small).
//
// Usage: node scripts/build-favicon.js [--out=path]

import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoOrthographic, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const land110 = require("world-atlas/land-110m.json");

const OCEAN = "#4A90B8";
const LAND = "#EDE0C8";
const COAST = "#3D2B1F";
const INK = "#111";

const SIZE = 64;
const R = 27; // globe radius
const C = 31; // globe centre; the shadow sits 3 units down-right of it
const SHADOW = 3;
const OUTLINE = 3;
// Atlantic view: both Americas on the left, Europe and Africa on the right,
// the silhouette people recognise as "Earth" fastest.
const ROTATE = [25, -18];
// Rings smaller than this (in square viewBox units) are invisible at 16px.
const MIN_AREA = 2.5;

const out =
  process.argv.find((a) => a.startsWith("--out="))?.slice(6) ??
  new URL("../public/favicon.svg", import.meta.url);

const projection = geoOrthographic()
  .rotate(ROTATE)
  .translate([C, C])
  .scale(R)
  .clipAngle(90);
const path = geoPath(projection).digits(1);

// Split the land into single polygons so tiny islands can be dropped one by one.
const land = feature(land110, land110.objects.land);
const polygons = land.features
  .flatMap(({ geometry: g }) => (g.type === "Polygon" ? [g.coordinates] : g.coordinates))
  .map((coordinates) => ({ type: "Polygon", coordinates }))
  .filter((p) => path.area(p) >= MIN_AREA);
const landPath = thin(
  path({ type: "MultiPolygon", coordinates: polygons.map((p) => p.coordinates) })
);

// The 110m coastline has far more vertices than 64 units can show. Drop any
// vertex within MIN_STEP of the last one kept, which cuts the file by ~80%
// with no visible change even at 128px.
function thin(d, MIN_STEP = 0.8) {
  return d
    .split("M")
    .filter(Boolean)
    .map((ring) => {
      const pts = ring.replace(/Z/g, "").split("L").map((p) => p.split(",").map(Number));
      const kept = [pts[0]];
      for (const p of pts.slice(1)) {
        const [x, y] = kept[kept.length - 1];
        if (Math.hypot(p[0] - x, p[1] - y) >= MIN_STEP) kept.push(p);
      }
      return kept.length > 2 ? "M" + kept.map((p) => p.join(",")).join("L") + "Z" : "";
    })
    .join("");
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}">
  <!-- Generated by scripts/build-favicon.js; edit that, not this file. -->
  <style>
    .ink { fill: ${INK}; stroke: ${INK}; }
    @media (prefers-color-scheme: dark) { .ink { fill: #FAF7F4; stroke: #FAF7F4; } }
  </style>
  <circle class="ink" cx="${C + SHADOW}" cy="${C + SHADOW}" r="${R}"/>
  <circle cx="${C}" cy="${C}" r="${R}" fill="${OCEAN}"/>
  <path d="${landPath}" fill="${LAND}" stroke="${COAST}" stroke-width="0.45" stroke-linejoin="round"/>
  <circle class="ink" cx="${C}" cy="${C}" r="${R}" style="fill: none" stroke-width="${OUTLINE}"/>
</svg>
`;

writeFileSync(out, svg);
console.log(`wrote ${out} (${svg.length} bytes, ${polygons.length} landmasses)`);
